#include <fstream>

#include "gtest/gtest.h"
#include "nlohmann/json.hpp"
#include "ament_index_cpp/get_package_share_directory.hpp"

#include "nav2_route/graph_file_loader.hpp"

using json = nlohmann::json;

TEST(GraphParser, test_graph_parser)
{
  std::string path_dir = "/home/josh/nav2_ws/src/navigation2/nav2_route/test/graph.geojson";

  std::ifstream graph_file(path_dir);

  ASSERT_TRUE(graph_file.is_open());

  json json;
  graph_file >> json;

  auto features = json.at("features");

  nav2_route::Graph graph;

  std::vector<nlohmann::json> nodes;
  std::vector<nlohmann::json> edges;
  for(const auto &feature : features)
  {
    if( feature["geometry"]["type"] == "Point")
    {
      nodes.emplace_back(feature);
    } else if ( feature["geometry"]["type"] == "LineString")
    {
      edges.emplace_back(feature);
    }
  }

  graph.resize(nodes.size());

  // Add nodes to graph
  for( const auto & node : nodes)
  {
    unsigned int id = node["properties"]["id"];
    std::string frame = node["properties"]["frame"];
    float x = node["geometry"]["coordinates"][0];
    float y = node["geometry"]["coordinates"][1];
    graph[id].nodeid = id;
    graph[id].coords.x = x;
    graph[id].coords.y = y;
    graph[id].coords.frame_id = frame;
  }

  // Add edges to graph
  nav2_route::EdgeCost default_cost;
  for (const auto & edge : edges)
  {
    unsigned int id = edge["properties"]["id"];
    unsigned int start_id = edge["properties"]["startid"];
    unsigned int end_id = edge["properties"]["endid"];
    graph[start_id].addEdge(default_cost, &graph[end_id], id);
  }
  // Validate the graph generated by the parser

  EXPECT_EQ(graph[0].neighbors.size(), 2u);
  EXPECT_EQ(graph[0].coords.frame_id, "map");
}

