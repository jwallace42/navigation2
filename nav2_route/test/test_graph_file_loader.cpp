void addNodesToGraph(nav2_route::Graph & graph, std::vector<nlohmann::json> & nodes)
{
  for (const auto & node : nodes) {
    // Required data
    unsigned int id = node["properties"]["id"];
    std::string frame = node["properties"]["frame"];
    float x = node["geometry"]["coordinates"][0];
    float y = node["geometry"]["coordinates"][1];
    graph[id].nodeid = id;
    graph[id].coords.x = x;
    graph[id].coords.y = y;
    graph[id].coords.frame_id = frame;

    // Meta data

  }
}

void addEdgesToGraph(nav2_route::Graph & graph, std::vector<nlohmann::json> & edges)
{
  nav2_route::EdgeCost edge_cost;
  for (const auto & edge : edges) {
    // Required data
    const auto edge_properties = edge["properties"];
    unsigned int id = edge_properties["id"];
    unsigned int start_id = edge_properties["startid"];
    unsigned int end_id = edge_properties["endid"];

    // Recommended data
    if ( edge_properties.contains("cost"))
    {
      edge_cost.cost = edge_properties["cost"];
    }

    if ( edge_properties.contains("overridable"))
    {
      edge_cost.overridable = edge_properties["overridable"];
    }

    // Meta data
    nav2_route::Metadata meta_data;
    if ( edge_properties.contains("meta_data"))
    {
      json json_meta_data = edge_properties["meta_data"];
      for (auto& [key, val] : json_meta_data.items())
      {
        std::cout << val.dump() << std::endl;
        meta_data.setValue(key, val);
      }
    }
    graph[start_id].addEdge(edge_cost, &graph[end_id], id, meta_data);
  }
}

TEST(GraphParser, test_graph_parser)
{
  std::string pkg_share_dir = ament_index_cpp::get_package_share_directory("nav2_route");
  std::string file_path = pkg_share_dir + "/graphs/geojson/simple_graph.geojson";

  std::ifstream graph_file(file_path);

  ASSERT_TRUE(graph_file.is_open());

  json json;
  graph_file >> json;

  auto features = json.at("features");

  std::vector<nlohmann::json> nodes;
  std::vector<nlohmann::json> edges;
  getNodes(features, nodes);
  getEdges(features, edges);

  nav2_route::Graph graph;
  graph.resize(nodes.size());
  addNodesToGraph(graph, nodes);
  addEdgesToGraph(graph, edges);

  // Validate the graph generated by the parser

  // Check node
  EXPECT_EQ(graph[0].coords.frame_id, "map");
  EXPECT_EQ(graph[0].coords.x, 0);
  EXPECT_EQ(graph[0].coords.y, 0);


  // Check edge
  EXPECT_EQ(graph[0].neighbors[0].end->nodeid, 1u);
  EXPECT_EQ(graph[0].neighbors[0].edgeid, 9u);
  EXPECT_EQ(graph[0].neighbors[0].edge_cost.cost, 6);
  EXPECT_EQ(graph[0].neighbors[0].edge_cost.overridable, true);

  // Edge meta data
//  float speed_limit = 0;
//  EXPECT_EQ(speed_limit, 0.85);
}
